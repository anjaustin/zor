"""
Fabric Compiler - Generates optimized CUDA kernels from frozen shapes

Features:
- Configurable optimization levels
- Multiple kernel variants (benchmark, production, debug)
- Automatic loop unrolling based on tile count
- Shared memory optimization
- Register pressure management
"""

import numpy as np
from pathlib import Path
from typing import List, Dict, Optional, Tuple
from dataclasses import dataclass
import subprocess
import tempfile
import shutil

from .config import FabricConfig, TaskConfig, OptimizationLevel
from .shapes import ShapeRegistry, Shape, get_registry


@dataclass
class CompiledTile:
    """A tile ready for CUDA compilation."""
    tile_id: int
    shape_name: str
    cuda_expr: str
    signature: np.ndarray
    round_constant: int


@dataclass
class CompiledFabric:
    """Complete compiled fabric."""
    tiles: List[CompiledTile]
    config: FabricConfig
    task: TaskConfig
    cuda_code: str
    binary_path: Optional[Path] = None


class FabricCompiler:
    """
    Compiles frozen shapes to optimized CUDA kernels.

    The compiler:
    1. Takes shape definitions from registry
    2. Generates signatures for routing
    3. Creates CUDA code with frozen dispatch
    4. Optionally compiles to binary
    """

    def __init__(self, config: FabricConfig, task: TaskConfig):
        self.config = config
        self.task = task
        self.registry = get_registry()

    def create_tiles(self) -> List[CompiledTile]:
        """Create tiles from task configuration."""
        tiles = []
        pattern = self.task.shape_pattern
        pattern_len = len(pattern)

        for i in range(self.config.num_tiles):
            shape_name = pattern[i % pattern_len]
            shape = self.registry.get(shape_name)

            tiles.append(CompiledTile(
                tile_id=i,
                shape_name=shape_name,
                cuda_expr=shape.cuda_expr,
                signature=shape.generate_signature(self.config.signature_bits, seed=i),
                round_constant=(i * 0x9E3779B9) & 0xFFFFFFFF,
            ))

        return tiles

    def generate_header(self) -> str:
        """Generate CUDA header with includes and defines."""
        opt_flags = {
            OptimizationLevel.DEBUG: "-G -g",
            OptimizationLevel.BALANCED: "-O2",
            OptimizationLevel.AGGRESSIVE: "-O3",
            OptimizationLevel.EXTREME: "-O3 --use_fast_math",
        }

        return f'''// =============================================================================
// FROZEN XOR FABRIC - Generated by TriX Pipeline v1.0
// =============================================================================
// Configuration:
//   Tiles: {self.config.num_tiles}
//   Signature bits: {self.config.signature_bits}
//   Block size: {self.config.block_size_bits} bits
//   Optimization: {self.config.optimization.name}
//   Compile: nvcc {opt_flags[self.config.optimization]} -o fabric fabric.cu
// =============================================================================

#include <cuda_runtime.h>
#include <stdio.h>
#include <stdint.h>
#include <chrono>

// Configuration constants
#define NUM_TILES {self.config.num_tiles}
#define SIGNATURE_BITS {self.config.signature_bits}
#define BLOCK_SIZE_BITS {self.config.block_size_bits}
#define BLOCK_SIZE_BYTES {self.config.block_size_bytes}
#define BLOCK_SIZE_WORDS {self.config.block_size_words}
#define THREADS_PER_BLOCK {self.config.threads_per_block}
#define TASK_ROUNDS {self.task.rounds}

'''

    def generate_signature_table(self, tiles: List[CompiledTile]) -> str:
        """Generate frozen routing table."""
        lines = ["// Frozen routing table - signatures for content-addressable lookup"]
        lines.append(f"__constant__ uint8_t tile_signatures[NUM_TILES][SIGNATURE_BITS] = {{")

        for tile in tiles:
            sig_str = ", ".join(str(b) for b in tile.signature)
            lines.append(f"    {{{sig_str}}},  // Tile {tile.tile_id}: {tile.shape_name}")

        lines.append("};")
        lines.append("")

        # Round constants
        lines.append("// Round constants (frozen)")
        for tile in tiles:
            lines.append(f"#define TILE_{tile.tile_id}_CONST 0x{tile.round_constant:08X}U")

        lines.append("")
        return "\n".join(lines)

    def generate_dispatch(self, tiles: List[CompiledTile]) -> str:
        """Generate frozen shape dispatch function."""
        lines = ["// Frozen shape dispatch - no runtime decisions"]
        lines.append("__device__ __forceinline__ uint32_t execute_tile(int tile_id, uint32_t a, uint32_t b) {")

        # Use switch for small tile counts, lookup table for large
        if self.config.num_tiles <= 64:
            lines.append("    switch (tile_id) {")
            for tile in tiles:
                const = f"TILE_{tile.tile_id}_CONST"
                expr = tile.cuda_expr
                # Handle complex expressions
                if "~" in expr and "(" not in expr:
                    expr = f"(~({expr.replace('~', '')}))"
                lines.append(f"        case {tile.tile_id}: return ({expr}) ^ {const};")
            lines.append("        default: return a ^ b;")
            lines.append("    }")
        else:
            # For large tile counts, use modular pattern
            lines.append(f"    int pattern_idx = tile_id % {len(self.task.shape_pattern)};")
            lines.append("    uint32_t k = tile_id * 0x9E3779B9U;")
            lines.append("    switch (pattern_idx) {")
            for i, shape_name in enumerate(self.task.shape_pattern):
                shape = self.registry.get(shape_name)
                lines.append(f"        case {i}: return ({shape.cuda_expr}) ^ k;")
            lines.append("        default: return a ^ b;")
            lines.append("    }")

        lines.append("}")
        lines.append("")
        return "\n".join(lines)

    def generate_kernel(self) -> str:
        """Generate main compute kernel."""
        words = self.config.block_size_words

        unroll = ""
        if self.config.optimization in [OptimizationLevel.AGGRESSIVE, OptimizationLevel.EXTREME]:
            unroll = "#pragma unroll"

        return f'''
// =============================================================================
// MAIN COMPUTE KERNEL
// =============================================================================

__global__ void fabric_execute(
    uint32_t* __restrict__ input,
    uint32_t* __restrict__ output,
    int num_blocks,
    int rounds
) {{
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx >= num_blocks) return;

    // Load block into registers
    uint32_t state[BLOCK_SIZE_WORDS];
    {unroll}
    for (int i = 0; i < BLOCK_SIZE_WORDS; i++) {{
        state[i] = input[idx * BLOCK_SIZE_WORDS + i];
    }}

    // Execute rounds
    for (int r = 0; r < rounds; r++) {{
        // Column rounds
        {unroll}
        for (int col = 0; col < 4; col++) {{
            int a = col, b = col + 4, c = col + 8, d = col + 12;
            if (d < BLOCK_SIZE_WORDS) {{
                state[a] = execute_tile((r * 4 + col) % NUM_TILES, state[a], state[b]);
                state[d] = execute_tile((r * 4 + col + 16) % NUM_TILES, state[d], state[a]);
                state[c] = execute_tile((r * 4 + col + 32) % NUM_TILES, state[c], state[d]);
                state[b] = execute_tile((r * 4 + col + 48) % NUM_TILES, state[b], state[c]);
            }}
        }}

        // Diagonal rounds (for 512-bit blocks)
        if (BLOCK_SIZE_WORDS >= 16) {{
            {unroll}
            for (int diag = 0; diag < 4; diag++) {{
                int a = diag;
                int b = ((diag + 1) % 4) + 4;
                int c = ((diag + 2) % 4) + 8;
                int d = ((diag + 3) % 4) + 12;
                state[a] = execute_tile((r * 4 + diag + 1) % NUM_TILES, state[a], state[b]);
                state[d] = execute_tile((r * 4 + diag + 17) % NUM_TILES, state[d], state[a]);
                state[c] = execute_tile((r * 4 + diag + 33) % NUM_TILES, state[c], state[d]);
                state[b] = execute_tile((r * 4 + diag + 49) % NUM_TILES, state[b], state[c]);
            }}
        }}
    }}

    // Store result
    {unroll}
    for (int i = 0; i < BLOCK_SIZE_WORDS; i++) {{
        output[idx * BLOCK_SIZE_WORDS + i] = state[i];
    }}
}}

// Optimized kernel for streaming (no output)
__global__ void fabric_execute_stream(
    uint32_t* __restrict__ data,
    int num_blocks,
    int rounds
) {{
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx >= num_blocks) return;

    uint32_t state[BLOCK_SIZE_WORDS];
    {unroll}
    for (int i = 0; i < BLOCK_SIZE_WORDS; i++) {{
        state[i] = data[idx * BLOCK_SIZE_WORDS + i];
    }}

    for (int r = 0; r < rounds; r++) {{
        {unroll}
        for (int col = 0; col < 4; col++) {{
            int a = col, b = col + 4, c = col + 8, d = col + 12;
            if (d < BLOCK_SIZE_WORDS) {{
                state[a] = execute_tile((r * 4 + col) % NUM_TILES, state[a], state[b]);
                state[d] = execute_tile((r * 4 + col + 16) % NUM_TILES, state[d], state[a]);
                state[c] = execute_tile((r * 4 + col + 32) % NUM_TILES, state[c], state[d]);
                state[b] = execute_tile((r * 4 + col + 48) % NUM_TILES, state[b], state[c]);
            }}
        }}
    }}

    {unroll}
    for (int i = 0; i < BLOCK_SIZE_WORDS; i++) {{
        data[idx * BLOCK_SIZE_WORDS + i] = state[i];
    }}
}}
'''

    def generate_benchmark(self) -> str:
        """Generate benchmark main function."""
        return '''
// =============================================================================
// BENCHMARK
// =============================================================================

void print_header() {
    printf("╔═══════════════════════════════════════════════════════════════════╗\\n");
    printf("║     FROZEN XOR FABRIC - Generated by TriX Pipeline               ║\\n");
    printf("╚═══════════════════════════════════════════════════════════════════╝\\n\\n");
}

void print_config() {
    printf("Configuration:\\n");
    printf("  Tiles: %d\\n", NUM_TILES);
    printf("  Signature bits: %d\\n", SIGNATURE_BITS);
    printf("  Block size: %d bits (%d bytes)\\n", BLOCK_SIZE_BITS, BLOCK_SIZE_BYTES);
    printf("  Rounds: %d\\n", TASK_ROUNDS);
    printf("\\n");
}

int main(int argc, char** argv) {
    print_header();

    cudaDeviceProp prop;
    cudaGetDeviceProperties(&prop, 0);
    printf("GPU: %s (%d SMs)\\n\\n", prop.name, prop.multiProcessorCount);

    print_config();

    // Parse arguments
    int num_blocks = 1 << 20;  // Default 1M blocks
    int iterations = 100;
    int warmup = 10;

    if (argc > 1) num_blocks = atoi(argv[1]);
    if (argc > 2) iterations = atoi(argv[2]);

    size_t data_size = (size_t)num_blocks * BLOCK_SIZE_BYTES;

    printf("Benchmark:\\n");
    printf("  Blocks: %d\\n", num_blocks);
    printf("  Data size: %.2f MB\\n", data_size / 1e6);
    printf("  Iterations: %d\\n\\n", iterations);

    // Allocate
    uint32_t *d_input, *d_output;
    cudaMalloc(&d_input, data_size);
    cudaMalloc(&d_output, data_size);
    cudaMemset(d_input, 0x55, data_size);

    cudaEvent_t start, stop;
    cudaEventCreate(&start);
    cudaEventCreate(&stop);

    int threads = THREADS_PER_BLOCK;
    int blocks = (num_blocks + threads - 1) / threads;

    // Warmup
    for (int i = 0; i < warmup; i++) {
        fabric_execute<<<blocks, threads>>>(d_input, d_output, num_blocks, TASK_ROUNDS);
    }
    cudaDeviceSynchronize();

    // Benchmark
    cudaEventRecord(start);
    for (int i = 0; i < iterations; i++) {
        fabric_execute<<<blocks, threads>>>(d_input, d_output, num_blocks, TASK_ROUNDS);
    }
    cudaEventRecord(stop);
    cudaEventSynchronize(stop);

    float ms;
    cudaEventElapsedTime(&ms, start, stop);

    // Calculate metrics
    double blocks_per_sec = (double)num_blocks * iterations / (ms / 1000.0);
    double bytes_per_sec = blocks_per_sec * BLOCK_SIZE_BYTES;
    double ops_per_block = TASK_ROUNDS * 8 * 4;  // 8 quarter rounds, 4 ops each
    double ops_per_sec = blocks_per_sec * ops_per_block;
    double bits_per_sec = blocks_per_sec * BLOCK_SIZE_BITS;

    printf("═══════════════════════════════════════════════════════════════════\\n");
    printf("RESULTS\\n");
    printf("═══════════════════════════════════════════════════════════════════\\n\\n");

    printf("  Time: %.2f ms\\n", ms);
    printf("  Throughput: %.2f GB/s\\n", bytes_per_sec / 1e9);
    printf("  Blocks/sec: %.2f M\\n", blocks_per_sec / 1e6);
    printf("  Shape ops/sec: %.2f G\\n", ops_per_sec / 1e9);
    printf("  Bits/sec: %.2f T\\n\\n", bits_per_sec / 1e12);

    // Per-round metrics
    double time_per_round = ms / (iterations * TASK_ROUNDS);
    printf("Per-round metrics:\\n");
    printf("  Time/round: %.3f us\\n", time_per_round * 1000);
    printf("  Throughput/round: %.2f GB/s\\n\\n", bytes_per_sec / 1e9 * TASK_ROUNDS);

    // Cleanup
    cudaFree(d_input);
    cudaFree(d_output);
    cudaEventDestroy(start);
    cudaEventDestroy(stop);

    return 0;
}
'''

    def compile(self) -> CompiledFabric:
        """Compile the fabric to CUDA code."""
        tiles = self.create_tiles()

        code_parts = [
            self.generate_header(),
            self.generate_signature_table(tiles),
            self.generate_dispatch(tiles),
            self.generate_kernel(),
            self.generate_benchmark(),
        ]

        cuda_code = "\n".join(code_parts)

        return CompiledFabric(
            tiles=tiles,
            config=self.config,
            task=self.task,
            cuda_code=cuda_code,
        )

    def compile_to_file(self, output_path: Path) -> CompiledFabric:
        """Compile and write to file."""
        fabric = self.compile()
        output_path.write_text(fabric.cuda_code)
        return fabric

    def compile_to_binary(self, output_path: Path) -> CompiledFabric:
        """Compile to CUDA binary."""
        fabric = self.compile()

        # Write CUDA source
        cuda_path = output_path.with_suffix(".cu")
        cuda_path.write_text(fabric.cuda_code)

        # Compile with nvcc
        opt_flags = {
            OptimizationLevel.DEBUG: ["-G", "-g"],
            OptimizationLevel.BALANCED: ["-O2"],
            OptimizationLevel.AGGRESSIVE: ["-O3"],
            OptimizationLevel.EXTREME: ["-O3", "--use_fast_math"],
        }

        cmd = ["nvcc"] + opt_flags[self.config.optimization] + [
            "-o", str(output_path),
            str(cuda_path),
        ]

        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            raise RuntimeError(f"CUDA compilation failed: {result.stderr}")

        fabric.binary_path = output_path
        return fabric
