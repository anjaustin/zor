#!/usr/bin/env python3
"""
GCS Compiler: YAML fabric specs -> C++ headers

The core tool of the Geometric Compute Shapes pipeline.
Transforms human-readable fabric definitions into GPU-executable code.

Usage:
    python gcs_compile.py fabrics/sorter_4.yaml > compiled/sorter_4.hpp
    python gcs_compile.py fabrics/sorter_4.yaml -o compiled/sorter_4.hpp

Based on the Lincoln Manifold synthesis: One tool, not six.
"""

import yaml
import sys
import argparse
from pathlib import Path
from typing import Dict, List, Tuple, Any

# Shape ID mapping (matches fabric_8x2.cu)
SHAPE_IDS = {
    'ADD': 0,
    'SUB': 1,
    'AND': 2,
    'OR': 3,
    'XOR': 4,
    'SHL': 5,
    'SHR': 6,
    'MUL': 7,
    'MIN': 8,
    'MAX': 9,
    'AVG': 10,
    'DIFF': 11,
    'PASS_A': 12,
    'PASS': 12,  # Alias
    'PASS_B': 13,
    'NOT': 14,
    'ZERO': 15,
    'NOP': 15,  # Alias
}

SHAPE_NAMES = [
    'ADD', 'SUB', 'AND', 'OR', 'XOR', 'SHL', 'SHR', 'MUL',
    'MIN', 'MAX', 'AVG', 'DIFF', 'PASS_A', 'PASS_B', 'NOT', 'ZERO'
]


def parse_source(src: str, current_layer: int) -> int:
    """
    Convert source reference to numeric index.

    Formats:
        'in.N'  -> N (input index 0-7)
        'L0.N'  -> N (layer 0 output, for layer 1+)
        'L1.N'  -> N (layer 1 output, for layer 2+)

    Note: For layer2, input indices 0-7 reference layer1 outputs (L0.N),
    not the original inputs.
    """
    src = src.strip()

    if src.startswith('in.'):
        return int(src[3:]) & 7

    elif src.startswith('L'):
        # L0.3 -> parse layer and node
        parts = src.split('.')
        layer = int(parts[0][1:])
        node = int(parts[1]) & 7

        # For layer2, L0 means layer1 outputs (index 0-7)
        # We just return the node index since layer2 input refs are 0-7
        return node

    elif src.isdigit():
        return int(src) & 7

    else:
        raise ValueError(f"Unknown source format: '{src}'")


def compile_fabric(spec: Dict[str, Any]) -> Tuple[str, Dict]:
    """
    Compile a fabric specification to C++ FabricConfig.

    Returns (c++ code, metadata dict)
    """
    fab = spec.get('fabric', spec)  # Handle both root and nested
    name = fab['name']
    inputs = fab.get('inputs', 8)
    outputs = fab.get('outputs', 8)

    # Initialize 8-wide arrays with NOP
    l1_shapes = [15] * 8
    l1_a = [0] * 8
    l1_b = [0] * 8
    l2_shapes = [15] * 8
    l2_a = [0] * 8
    l2_b = [0] * 8

    # Parse layers
    layers = fab.get('layers', [])

    if len(layers) >= 1:
        layer0 = layers[0]
        nodes = layer0.get('nodes', [])
        for i, node in enumerate(nodes):
            if i >= 8:
                print(f"Warning: Layer 0 has more than 8 nodes, ignoring extras", file=sys.stderr)
                break

            shape_name = node.get('shape', 'NOP').upper()
            if shape_name not in SHAPE_IDS:
                raise ValueError(f"Unknown shape: {shape_name}")

            l1_shapes[i] = SHAPE_IDS[shape_name]
            l1_a[i] = parse_source(node.get('a', node.get('inputs', ['in.0'])[0] if 'inputs' in node else 'in.0'), 0)
            l1_b[i] = parse_source(node.get('b', node.get('inputs', ['in.0', 'in.0'])[1] if 'inputs' in node and len(node.get('inputs', [])) > 1 else 'in.0'), 0)

    if len(layers) >= 2:
        layer1 = layers[1]
        nodes = layer1.get('nodes', [])
        for i, node in enumerate(nodes):
            if i >= 8:
                print(f"Warning: Layer 1 has more than 8 nodes, ignoring extras", file=sys.stderr)
                break

            shape_name = node.get('shape', 'NOP').upper()
            if shape_name not in SHAPE_IDS:
                raise ValueError(f"Unknown shape: {shape_name}")

            l2_shapes[i] = SHAPE_IDS[shape_name]
            l2_a[i] = parse_source(node.get('a', node.get('inputs', ['L0.0'])[0] if 'inputs' in node else 'L0.0'), 1)
            l2_b[i] = parse_source(node.get('b', node.get('inputs', ['L0.0', 'L0.0'])[1] if 'inputs' in node and len(node.get('inputs', [])) > 1 else 'L0.0'), 1)

    # Generate C++ code
    def fmt_array(arr):
        return ', '.join(str(x) for x in arr)

    # Generate human-readable comments
    l1_comments = []
    for i in range(8):
        if l1_shapes[i] != 15:  # Not NOP
            l1_comments.append(f"// ALU{i}: {SHAPE_NAMES[l1_shapes[i]]}(in[{l1_a[i]}], in[{l1_b[i]}])")

    l2_comments = []
    for i in range(8):
        if l2_shapes[i] != 15:  # Not NOP
            l2_comments.append(f"// ALU{i}: {SHAPE_NAMES[l2_shapes[i]]}(L0[{l2_a[i]}], L0[{l2_b[i]}])")

    code = f'''// AUTO-GENERATED by gcs-compile
// Source: {name}
// DO NOT EDIT - Regenerate from YAML source

#pragma once

namespace gcs {{
namespace {name} {{

// Layer 1 configuration
{chr(10).join(l1_comments)}

// Layer 2 configuration
{chr(10).join(l2_comments)}

constexpr struct {{
    uint8_t layer1_shapes[8] = {{{fmt_array(l1_shapes)}}};
    uint8_t layer1_input_a[8] = {{{fmt_array(l1_a)}}};
    uint8_t layer1_input_b[8] = {{{fmt_array(l1_b)}}};
    uint8_t layer2_shapes[8] = {{{fmt_array(l2_shapes)}}};
    uint8_t layer2_input_a[8] = {{{fmt_array(l2_a)}}};
    uint8_t layer2_input_b[8] = {{{fmt_array(l2_b)}}};
}} CONFIG;

// Convert to FabricConfig (for use with fabric_8x2.cu)
inline FabricConfig to_fabric_config() {{
    FabricConfig c;
    for (int i = 0; i < 8; i++) {{
        c.layer1_shapes[i] = CONFIG.layer1_shapes[i];
        c.layer1_input_a[i] = CONFIG.layer1_input_a[i];
        c.layer1_input_b[i] = CONFIG.layer1_input_b[i];
        c.layer2_shapes[i] = CONFIG.layer2_shapes[i];
        c.layer2_input_a[i] = CONFIG.layer2_input_a[i];
        c.layer2_input_b[i] = CONFIG.layer2_input_b[i];
    }}
    return c;
}}

}} // namespace {name}
}} // namespace gcs
'''

    metadata = {
        'name': name,
        'inputs': inputs,
        'outputs': outputs,
        'layer1_active': sum(1 for s in l1_shapes if s != 15),
        'layer2_active': sum(1 for s in l2_shapes if s != 15),
    }

    return code, metadata


def main():
    parser = argparse.ArgumentParser(description='GCS Compiler: YAML -> C++ header')
    parser.add_argument('input', help='Input YAML fabric spec')
    parser.add_argument('-o', '--output', help='Output C++ header (default: stdout)')
    parser.add_argument('-v', '--verbose', action='store_true', help='Print metadata')

    args = parser.parse_args()

    # Read and parse YAML
    with open(args.input) as f:
        spec = yaml.safe_load(f)

    # Compile
    code, metadata = compile_fabric(spec)

    # Output
    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        with open(args.output, 'w') as f:
            f.write(code)
        if args.verbose:
            print(f"Compiled: {args.input} -> {args.output}", file=sys.stderr)
            print(f"  Name: {metadata['name']}", file=sys.stderr)
            print(f"  Inputs: {metadata['inputs']}", file=sys.stderr)
            print(f"  Layer 1: {metadata['layer1_active']} active nodes", file=sys.stderr)
            print(f"  Layer 2: {metadata['layer2_active']} active nodes", file=sys.stderr)
    else:
        print(code)


if __name__ == '__main__':
    main()
